"""Generate the slash command reference from the directive registry."""

from __future__ import annotations

import html
import pathlib

from agent6 import directive

_INTRO = """<!-- Generated by docs/gen_slash_commands.py from agent6.directive.COMMANDS. -->

# Slash commands

**Accepted** lists the places where the command acts.
**Refused** lists places that reject it instead of sending it to the model.
At a task or steer input, a word in neither column is plain text.
The CLI menus also check for unknown command words.

- **start**: the first task of a run.
- **plan/ask**: the first task of a plan or ask.
- **pause**: the CLI pause menu.
- **steer** and **resume**: the TUI and web composers for a live or ended run.
- **script**: `agent6 steer`.
- **acp start** and **acp**: the editor's first prompt and its later prompts.
- **parent**: a steer sent by a parent to a child, always text.
- **child**: the task in a child's launch file.
- **run -i**: the commit prompt.
- **ask -i**: the interactive ask prompt.
- **next**: the end-of-session prompt, which refuses a lone slash word except `/undo` and `/exit`.

A valid opening `/parallel` is text in a plan, an ask or a child's task.
The editor offers child dispatch only in modes that can dispatch work.
The web composer withholds `/undo` under model git control.
Use the name of an enabled skill in place of `/<skill>`.

| Usage | Help | Kind | Accepted | Refused |
| --- | --- | --- | --- | --- |"""


def _cell(text: str) -> str:
    """Return literal command text that fits in one Markdown cell."""
    return html.escape(text, quote=False).replace("|", "&#124;")


def build_markdown() -> str:
    """Return the operator's command reference in command-name order."""
    lines = [_INTRO]
    for command in sorted(directive.COMMANDS, key=lambda c: c.name):
        accepts = ", ".join(sorted(command.accepts))
        refuses = ", ".join(sorted(command.refuses)) or "-"
        lines.append(
            f"| <code>{_cell(command.usage)}</code> | {_cell(command.help)} | {command.kind}"
            f" | {accepts} | {refuses} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    pathlib.Path(__file__).with_name("slash-commands.md").write_text(
        build_markdown(), encoding="utf-8"
    )
